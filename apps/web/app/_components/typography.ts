// Переносы в коротких текстах лендинга и экранов: тире не начинает строку, однобуквенные и двухбуквенные слова
// (предлоги, союзы, частицы) не остаются в конце строки. Работает на любом языке каталога — правит готовую строку.
const NBSP = " ";

/** «На каждом месте — новая тема» → неразрывный пробел перед тире и после коротких слов. */
export function keepTogether(text: string): string {
  return text.replace(/ (?=[—–])/g, NBSP).replace(/(?<=^|[\s«(])(\p{L}{1,2}) /gu, `$1${NBSP}`);
}
