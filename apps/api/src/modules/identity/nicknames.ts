const GENDER_FORM: Record<Gender, 0 | 1 | 2> = { m: 0, f: 1, n: 2 };
const pad = (n: number) => String(n).padStart(2, "0");
const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

export interface Nickname {
  id: string;
  text: string;
}

/** Текст ника по идентификатору `aNN.nNN` или undefined, если такого ника нет. */
export function nicknameById(id: string): Nickname | undefined {
  const m = /^a(\d{2})\.n(\d{2})$/.exec(id);
  if (!m) return undefined;
  const adj = ADJECTIVES[Number(m[1])];
  const noun = NOUNS[Number(m[2])];
  if (!adj || !noun) return undefined;
  return { id, text: capitalize(`${adj[GENDER_FORM[noun[1]]]} ${noun[0]}`) };
}

/** Число разных ников в словаре. */
export const NICKNAME_COUNT = ADJECTIVES.length * NOUNS.length;

/** `count` разных случайных ников (криптостойкий ГСЧ). */
export function suggestNicknames(count: number): Nickname[] {
  const ids = new Set<string>();
  while (ids.size < Math.min(count, NICKNAME_COUNT)) ids.add(`a${pad(randomInt(ADJECTIVES.length))}.n${pad(randomInt(NOUNS.length))}`);
  return [...ids].map((id) => nicknameById(id)!);
}

/** Все ники (для тестов словаря). */
export function allNicknames(): Nickname[] {
  return ADJECTIVES.flatMap((_, a) => NOUNS.map((__, n) => nicknameById(`a${pad(a)}.n${pad(n)}`)!));
}
