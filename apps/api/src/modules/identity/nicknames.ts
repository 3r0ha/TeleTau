// Словарь ников «прилагательное + существительное» (ADR 0009): ребёнок не вводит ничего своего, только выбирает.
// Только русский язык — башкирские ники появятся после проверки носителем (CLAUDE.md, правило 6).
// Ник нейтрален к полу ребёнка: существительные — животные, птицы, растения и явления природы, а прилагательное
// согласуется с грамматическим родом существительного, а не ребёнка. Прилагательные — только добрые и нейтральные.
// Идентификатор ника — `aNN.nNN` (индексы в списках): списки только дополняются в конец, порядок не меняется.
