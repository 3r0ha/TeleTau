// Действующие версии юридических документов (сид таблицы legal_documents при старте API).
// Тексты — черновик разработчика (юридическая вычитка вне скоупа, CLAUDE.md правило 16).
// Версия документа неизменяема: новый текст — новая версия с новой датой; старые версии остаются в базе,
// потому что на них ссылаются данные согласия. SHA-256 текста хранится в legal_documents.body_sha256.
import type { Schema } from "@teletau/contracts";

export type LegalDocumentKind = Schema<"LegalDocumentKind">;

export interface LegalText {
  kind: LegalDocumentKind;
  version: string;
  title: string;
  /** Начало действия (UTC). */
  effectiveFrom: string;
  /** Абзацы текста. */
  body: string[];
}

